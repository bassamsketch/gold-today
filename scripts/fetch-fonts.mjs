// Download the Latin and Arabic WOFF2 subsets of the app fonts and write app/css/fonts.css (design D6).
import { mkdirSync, writeFileSync } from 'node:fs';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const FAMILIES = [
  { q: 'Source+Serif+4:opsz,wght@24,500;24,600', keep: ['latin'] },
  { q: 'Amiri:wght@700', keep: ['arabic', 'latin'] },
  { q: 'Almarai:wght@400;700', keep: ['arabic', 'latin'] },
];
const out = new URL('../app/fonts/', import.meta.url);
mkdirSync(out, { recursive: true });

let css = '/* Self-hosted subsets of Google Fonts (SIL Open Font License). Generated by scripts/fetch-fonts.mjs */\n';
let total = 0;
for (const fam of FAMILIES) {
  const text = await (await fetch(`https://fonts.googleapis.com/css2?family=${fam.q}&display=swap`, { headers: { 'User-Agent': UA } })).text();
  // Each block is preceded by a /* subset */ comment.
  for (const m of text.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]+)\}/g)) {
    const [, subset, body] = m;
    if (!fam.keep.includes(subset)) continue;
    const family = body.match(/font-family: '([^']+)'/)[1];
    const style = body.match(/font-style: (\w+)/)[1];
    const weight = body.match(/font-weight: ([\d ]+)/)[1].trim();
    const url = body.match(/url\((https:[^)]+)\)/)[1];
    const range = body.match(/unicode-range: ([^;]+);/)[1];
    const file = `${family.replace(/\s+/g, '')}-${style}-${weight.replace(' ', '_')}-${subset}.woff2`;
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    writeFileSync(new URL(file, out), buf);
    total += buf.length;
    css += `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url(../fonts/${file}) format('woff2');unicode-range:${range}}\n`;
    console.log(`${file}  ${(buf.length / 1024).toFixed(1)} KB`);
  }
}
writeFileSync(new URL('../app/css/fonts.css', import.meta.url), css);
console.log(`total ${(total / 1024).toFixed(1)} KB`);
